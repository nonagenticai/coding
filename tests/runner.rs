//! Integration tests for the in-pod runner: the spec, the source materialisation and the
//! result contract, without a cluster and without a Pod.
//!
//! The two `cargo` tests build a real (dependency-free) crate in a temp dir. They are what proves
//! the exit-code rule end to end: a failing test is a *result* with `status: failed`, not a
//! broken runner.

use std::path::{Path, PathBuf};

use coding::domain::{InlineFile, JobInput, JobKind, Source};
use coding::runner::exec::{self, Cancellation};
use coding::runner::result::Status;
use coding::runner::spec::RunnerSpec;

fn spec(kind: JobKind, source: Option<Source>) -> RunnerSpec {
    RunnerSpec {
        job_id: "job-test".to_owned(),
        tenant_id: "tenant-test".to_owned(),
        kind,
        attempt: 1,
        workspace_id: None,
        deadline_seconds: 120,
        input: JobInput {
            source,
            ..Default::default()
        },
    }
}

fn crate_source(failing: bool) -> Source {
    // `crate::add`, not `sample::add`: these are unit tests inside the crate itself.
    let assertion = if failing { 4 } else { 3 };
    let lib = format!(
        "pub fn add(a: i32, b: i32) -> i32 {{\n    a + b\n}}\n\n\
         #[cfg(test)]\nmod tests {{\n    #[test]\n    fn adds() {{\n        \
         assert_eq!(crate::add(1, 2), {assertion});\n    }}\n}}\n"
    );
    Source::Inline {
        files: vec![
            InlineFile {
                path: "Cargo.toml".to_owned(),
                text: "[package]\nname = \"sample\"\nversion = \"0.1.0\"\nedition = \"2021\"\n"
                    .to_owned(),
            },
            InlineFile {
                path: "Cargo.lock".to_owned(),
                text: "# This file is automatically @generated by Cargo.\nversion = 4\n\n\
                       [[package]]\nname = \"sample\"\nversion = \"0.1.0\"\n"
                    .to_owned(),
            },
            InlineFile {
                path: "src/lib.rs".to_owned(),
                text: lib,
            },
        ],
    }
}

/// A per-test work directory, removed when the guard drops.
struct WorkDir(PathBuf);

impl WorkDir {
    fn new(name: &str) -> Self {
        let path =
            std::env::temp_dir().join(format!("coding-runner-{}-{name}", std::process::id()));
        let _ = std::fs::remove_dir_all(&path);
        Self(path)
    }

    fn source(&self) -> &Path {
        &self.0
    }
}

impl Drop for WorkDir {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
        let _ = std::fs::remove_dir_all(format!("{}.target", self.0.display()));
    }
}

#[tokio::test]
async fn a_kind_without_a_plan_is_unsupported() {
    let work = WorkDir::new("unsupported");
    let mut cancel = Cancellation::new().expect("signal handler");
    let result = exec::run_in(
        &spec(JobKind::Scan, Some(crate_source(false))),
        &mut cancel,
        work.source(),
    )
    .await;
    assert_eq!(result.status, Status::Unsupported);
    assert!(result.checks.is_empty());
}

#[tokio::test]
async fn a_passing_crate_reports_succeeded_with_an_exit_code() {
    let work = WorkDir::new("passing");
    let mut cancel = Cancellation::new().expect("signal handler");
    let result = exec::run_in(
        &spec(JobKind::Test, Some(crate_source(false))),
        &mut cancel,
        work.source(),
    )
    .await;
    assert_eq!(result.status, Status::Succeeded, "{result:?}");
    assert_eq!(result.checks.len(), 1);
    assert_eq!(result.checks[0].name, "cargo test");
    assert_eq!(result.checks[0].exit_code, Some(0));
    assert!(result.source.is_some());
}

#[tokio::test]
async fn a_failing_crate_is_a_failed_result_not_a_crash() {
    let work = WorkDir::new("failing");
    let mut cancel = Cancellation::new().expect("signal handler");
    let result = exec::run_in(
        &spec(JobKind::Test, Some(crate_source(true))),
        &mut cancel,
        work.source(),
    )
    .await;
    assert_eq!(result.status, Status::Failed, "{result:?}");
    assert_eq!(result.checks.len(), 1);
    // cargo test exits 101 on a failing test.
    assert_eq!(result.checks[0].exit_code, Some(101));
    assert!(
        result.error.is_none(),
        "a failing test is not a setup error"
    );
}

