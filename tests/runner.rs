/// A `check` job runs every gate in one Pod — lint, then the same test plan CI runs — and
/// reports each step. The four names are the assertion: when `check` was a hand-written copy it
/// kept a plain `cargo test` long after the `test` kind moved to nextest.
#[tokio::test]
async fn a_check_job_runs_fmt_clippy_and_test() {
    let work = WorkDir::new("check");
    let mut cancel = Cancellation::new().expect("signal handler");
    let result = exec::run_in(
        &spec(JobKind::Check, Some(crate_source(false))),
        &mut cancel,
        work.source(),
    )
    .await;
    assert_eq!(result.status, Status::Succeeded, "{result:?}");
    let names: Vec<&str> = result.checks.iter().map(|c| c.name.as_str()).collect();
    assert_eq!(
        names,
        [
            "cargo fmt",
            "cargo clippy",
            "cargo test --doc",
            "cargo nextest"
        ]
    );
    for check in &result.checks {
        assert_eq!(check.exit_code, Some(0), "{check:?}");
        assert!(
            check.output_tail.is_none(),
            "a passing check carries no tail"
        );
    }
}

/// A failing check carries the tail of its own output: the reason a developer can act on.
#[tokio::test]
async fn a_failing_check_carries_its_output_tail() {
    let work = WorkDir::new("tail");
    let mut cancel = Cancellation::new().expect("signal handler");
    let result = exec::run_in(
        &spec(JobKind::Test, Some(crate_source(true))),
        &mut cancel,
        work.source(),
    )
    .await;
    assert_eq!(result.status, Status::Failed, "{result:?}");
    let tail = result.checks[1]
        .output_tail
        .as_deref()
        .expect("the failing check must carry its tail");
    // nextest's own framing plus the panic it captured, not a bare summary line.
    assert!(
        tail.contains("assertion") || tail.contains("panicked") || tail.contains("FAIL"),
        "the tail is the test output, not a summary: {tail}"
    );
    assert!(
        tail.len() <= coding::runner::result::MAX_CHECK_OUTPUT_BYTES,
        "the tail is bounded"
    );
}

fn sources_spec(kind: JobKind, list: &[(&str, Profile, Source)]) -> RunnerSpec {
    let mut spec = spec(kind, None);
    spec.input.sources = list
        .iter()
        .map(|(name, profile, source)| NamedSource {
            name: (*name).to_owned(),
            profile: *profile,
            source: source.clone(),
        })
        .collect();
    spec
}

/// One job, two trees: both plans run, and every check says which tree it belongs to.
#[tokio::test]
async fn a_two_source_job_runs_both_plans_and_names_each_check() {
    let work = WorkDir::new("two-sources");
    let mut cancel = Cancellation::new().expect("signal handler");
    let result = exec::run_in(
        &sources_spec(
            JobKind::Test,
            &[
                ("target", Profile::Rust, crate_source(false)),
                ("source-1", Profile::Rust, crate_source(true)),
            ],
        ),
        &mut cancel,
        work.source(),
    )
    .await;

    assert_eq!(result.status, Status::Failed, "{result:?}");
    // The Rust test plan is two steps — doctests, then the suite — so each tree reports two.
    assert_eq!(result.checks.len(), 4, "two test steps per source");
    assert_eq!(result.checks[0].source.as_deref(), Some("target"));
    assert_eq!(result.checks[1].source.as_deref(), Some("target"));
    assert_eq!(result.checks[2].source.as_deref(), Some("source-1"));
    assert_eq!(result.checks[3].source.as_deref(), Some("source-1"));
    assert_eq!(
        result.checks[0].status,
        coding::runner::result::CheckStatus::Passed
    );
    assert_eq!(
        result.checks[3].status,
        coding::runner::result::CheckStatus::Failed
    );
    // Both plans ran: the second source's failure did not stop the job from reporting the first.
    assert!(
        result.summary.contains("source-1"),
        "the summary names the failing source: {}",
        result.summary
    );
    // The single-source fields stay out of a multi-source result.
    assert!(result.source.is_none());
    let names: Vec<&str> = result
        .sources
        .iter()
        .filter_map(|source| source.name.as_deref())
        .collect();
    assert_eq!(names, ["target", "source-1"]);
    // Each tree was materialised under its own name.
    assert!(work.source().join("sources/target/Cargo.toml").is_file());
    assert!(work.source().join("sources/source-1/Cargo.toml").is_file());
}

/// A source whose tree is not its profile's is refused before any plan runs: an unset marker is
/// a request mistake, not a failing check about the code.
#[tokio::test]
async fn a_second_source_without_its_marker_is_unsupported_before_any_step() {
    let work = WorkDir::new("second-marker");
    let mut cancel = Cancellation::new().expect("signal handler");
    let result = exec::run_in(
        &sources_spec(
            JobKind::Check,
            &[
                ("target", Profile::Rust, crate_source(false)),
                // No pyproject.toml: the python profile cannot run on this tree.
                ("source-1", Profile::Python, crate_source(false)),
            ],
        ),
        &mut cancel,
        work.source(),
    )
    .await;

    assert_eq!(result.status, Status::Unsupported, "{result:?}");
    assert!(result.checks.is_empty(), "nothing ran: {result:?}");
    assert!(
        result.summary.contains("source-1") && result.summary.contains("pyproject.toml"),
        "the verdict names the source and the missing marker: {}",
        result.summary
    );
}

/// A crate whose single test blocks far longer than the job's deadline.
fn slow_source(seconds: u64) -> Source {
    let lib = format!(
        "pub fn add(a: i32, b: i32) -> i32 {{
    a + b
}}

#[cfg(test)]
mod tests {{
    #[test]
    fn sleeps() {{
        std::thread::sleep(std::time::Duration::from_secs({seconds}));
    }}
}}
"
    );
    Source::Inline {
        files: vec![
            InlineFile {
                path: "Cargo.toml".to_owned(),
                text: "[package]\nname = \"sample\"\nversion = \"0.1.0\"\nedition = \"2021\"\n"
                    .to_owned(),
            },
            InlineFile {
                path: "Cargo.lock".to_owned(),
                text: "# This file is automatically @generated by Cargo.\nversion = 4\n\n\
                       [[package]]\nname = \"sample\"\nversion = \"0.1.0\"\n"
                    .to_owned(),
            },
            InlineFile {
                path: "src/lib.rs".to_owned(),
                text: lib,
            },
        ],
    }
}

/// A timeout is a whole-job outcome, but the message must still say which source hung: with
/// several plans in one Pod, "the deadline was exceeded during cargo test" names no tree.
#[tokio::test]
async fn a_timeout_names_the_source_it_happened_in() {
    let work = WorkDir::new("timeout-source");
    let mut cancel = Cancellation::new().expect("signal handler");
    let mut spec = sources_spec(
        JobKind::Test,
        &[
            ("fast", Profile::Rust, crate_source(false)),
            ("slow", Profile::Rust, slow_source(60)),
        ],
    );
    spec.deadline_seconds = 10;
    let result = exec::run_in(&spec, &mut cancel, work.source()).await;
    assert_eq!(result.status, Status::Timeout, "{result:?}");
    assert!(
        result.summary.contains("source \"slow\""),
        "the verdict names the source that hung: {}",
        result.summary
    );
}

/// The upload source's fetch address, as only the worker will supply it.
const UPLOAD_ID: &str = "6f1a1f6a-1d3a-4f2c-9a1e-2f4a1b7c8d90";
const UPLOAD_TOKEN: &str = "0123456789abcdef0123456789abcdef";

/// A **real** HTTP server on a random port. The runner's download path is exercised end to end:
/// no mocked transport, no injected client.
async fn serve_archive(blob: Vec<u8>) -> String {
    use axum::response::IntoResponse;
    let app = axum::Router::new().route(
        "/api/sources/{id}/blob",
        axum::routing::get(move |headers: axum::http::HeaderMap| {
            let blob = blob.clone();
            async move {
                let presented = headers
                    .get("x-source-token")
                    .and_then(|value| value.to_str().ok());
                if presented == Some(UPLOAD_TOKEN) {
                    (axum::http::StatusCode::OK, blob).into_response()
                } else {
                    (axum::http::StatusCode::NOT_FOUND, Vec::new()).into_response()
                }
            }
        }),
    );
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0")
        .await
        .expect("bind a loopback port");
    let addr = listener.local_addr().expect("local addr");
    tokio::spawn(async move {
        let _ = axum::serve(listener, app).await;
    });
    format!("http://{addr}/api/sources/{UPLOAD_ID}/blob")
}

/// The inline fixture, as the archive a client would upload.
fn archived_crate(failing: bool) -> Vec<u8> {
    let Source::Inline { files } = crate_source(failing) else {
        panic!("the fixture is an inline source");
    };
    let packed: Vec<coding::source_archive::PackFile> = files
        .into_iter()
        .map(|file| coding::source_archive::PackFile {
            path: file.path,
            data: file.text.into_bytes(),
            executable: false,
        })
        .collect();
    coding::source_archive::pack(&packed).expect("pack")
}

fn upload_source(url: String, sha256: String, token: &str) -> Source {
    Source::Upload {
        id: UPLOAD_ID.to_owned(),
        url: Some(url),
        token: Some(token.to_owned()),
        sha256: Some(sha256),
    }
}

#[tokio::test]
async fn an_uploaded_archive_is_fetched_verified_and_unpacked() {
    let blob = archived_crate(false);
    let sha256 = coding::source_archive::sha256_hex(&blob);
    let url = serve_archive(blob.clone()).await;
    let work = WorkDir::new("upload");
    let mut cancel = Cancellation::new().expect("signal handler");

    let result = exec::run_in(
        &spec(
            JobKind::Test,
            Some(upload_source(url, sha256, UPLOAD_TOKEN)),
        ),
        &mut cancel,
        work.source(),
    )
    .await;

    assert_eq!(result.status, Status::Succeeded, "{result:?}");
    assert_eq!(result.checks[0].name, "cargo test --doc");
    let source = result.source.expect("a result names its source");
    assert_eq!(source.kind, "upload");
    assert_eq!(source.files, 3, "the archive's own file count");
    // A single-source job's tree lands at `<work base>/src`, exactly where the Pod writes it.
    let unpacked = std::fs::read_to_string(work.source().join("src/src/lib.rs")).expect("unpacked");
    assert!(
        unpacked.contains("pub fn add"),
        "the working tree came out of the archive: {unpacked}"
    );
}

#[tokio::test]
async fn a_transient_fetch_failure_is_retried() {
    // The kata startup race, reproduced deterministically: the first connections are accepted and
    // closed without a response, exactly as a guest network that is not up yet behaves.
    let blob = archived_crate(false);
    let sha256 = coding::source_archive::sha256_hex(&blob);
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0")
        .await
        .expect("bind a loopback port");
    let addr = listener.local_addr().expect("local addr");
    let app = {
        use axum::response::IntoResponse;
        let blob = blob.clone();
        axum::Router::new().route(
            "/api/sources/{id}/blob",
            axum::routing::get(move |headers: axum::http::HeaderMap| {
                let blob = blob.clone();
                async move {
                    if headers
                        .get("x-source-token")
                        .and_then(|value| value.to_str().ok())
                        == Some(UPLOAD_TOKEN)
                    {
                        (axum::http::StatusCode::OK, blob).into_response()
                    } else {
                        (axum::http::StatusCode::NOT_FOUND, Vec::new()).into_response()
                    }
                }
            }),
        )
    };
    tokio::spawn(async move {
        for _ in 0..2 {
            let (stream, _) = listener.accept().await.expect("accept");
            drop(stream);
        }
        let _ = axum::serve(listener, app).await;
    });
    let url = format!("http://{addr}/api/sources/{UPLOAD_ID}/blob");

    let work = WorkDir::new("upload-retry");
    let mut cancel = Cancellation::new().expect("signal handler");
    let result = exec::run_in(
        &spec(
            JobKind::Test,
            Some(upload_source(url, sha256, UPLOAD_TOKEN)),
        ),
        &mut cancel,
        work.source(),
    )
    .await;

    assert_eq!(
        result.status,
        Status::Succeeded,
        "two refused connections must not fail the job: {result:?}"
    );
    assert_eq!(result.checks[0].name, "cargo test --doc");
}

#[tokio::test]
async fn a_download_that_does_not_match_its_hash_stops_before_any_check() {
    let blob = archived_crate(false);
    let wrong = "0".repeat(64);
    let url = serve_archive(blob).await;
    let work = WorkDir::new("upload-hash");
    let mut cancel = Cancellation::new().expect("signal handler");

    let result = exec::run_in(
        &spec(JobKind::Test, Some(upload_source(url, wrong, UPLOAD_TOKEN))),
        &mut cancel,
        work.source(),
    )
    .await;

    assert_eq!(result.status, Status::Failed, "{result:?}");
    assert!(result.checks.is_empty(), "nothing ran");
    assert!(
        result
            .error
            .as_deref()
            .unwrap_or_default()
            .contains("hashes to"),
        "{result:?}"
    );
}

